/*
 * 2018 放硬币
 *
 * 题目要求：
 * 小明手里有 m 个完全相同的 1 元硬币，另有 n 个完全一样的存钱罐，
 * 把硬币放到存钱罐中（允许有空罐），问有多少种不同放法。
 * 例如 3 个硬币、3 个存钱罐：(1,1,1)、(2,1,0)、(3,0,0)，共 3 种。
 *
 * 输入格式：
 * 输入 m、n（1 ≤ n, m ≤ 10）。
 *
 * 输出格式：
 * 输出放法种类数。
 *
 * 输入样例：
 * 3 3
 *
 * 输出样例：
 * 3
 *
 * 错题复盘（评测 2 次）：首次提交 10 组测试全部不匹配。
 *
 * 【错误代码（首次提交，边界返回语句）】
 *   if (m == 0)
 *       returm 1;          // return 误拼为 returm，关键字拼写错误
 *
 * 【错因】返回关键字 `return` 拼写成 `returm`，编译/识别失败。
 * 【修正】改回 `return 1;` 后通过，即下方代码。
 *
 * 【递归思路】f(m, n) 表示 m 枚硬币分进 n 个可空罐子的分拆数：
 *  m==0 硬币分完 → 1 种；n==1 只剩一个罐子 → 1 种；
 *  n>m 罐子多于硬币 → 等价 f(m, m)；
 *  否则 f(m, n-1)（第 n 罐不放）+ f(m-n, n)（第 n 罐至少放 1 枚）。
 */

#include <iostream>
using namespace std;

int f(int m, int n)
{
    if (m == 0)
        return 1;
    if (n == 1)
        return 1;
    if (n > m)
        return f(m, m);
    return f(m, n - 1) + f(m - n, n);
}

int main()
{
    int m, n;
    cin >> m >> n;
    cout << f(m, n) << endl;
    return 0;
}
