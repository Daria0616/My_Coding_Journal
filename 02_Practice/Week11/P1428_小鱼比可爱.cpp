/*
 * P1428 小鱼比可爱
 *
 * 题目要求：
 * 小鱼从左到右排成一排，头都朝向左边，每只鱼有一个可爱程度数值（越大越可爱，
 * 可能相同）。每只鱼只能看见它左边的鱼，计算在自己眼力范围内有多少只鱼
 * 不如自己可爱。
 *
 * 输入格式：
 * 第一行输入正整数 n（鱼的数目）；
 * 第二行输入 n 个非负整数，依次表示从左到右每只小鱼的可爱程度。
 *
 * 输出格式：
 * 一行输出 n 个整数，用空格隔开，依次表示每只小鱼眼中不如自己可爱的鱼的数量。
 *
 * 输入样例：
 * 6
 * 4 3 0 5 1 2
 *
 * 输出样例：
 * 0 0 0 3 1 2
 *
 * 数据范围：1 ≤ n ≤ 100，0 ≤ a_i ≤ 10。
 * 本关一次评测通过，无失败记录。
 */

#include <iostream>
using namespace std;

int main()
{
    int n;
    int arr[110];

    cin >> n;
    for (int i = 0; i < n; i++)
        cin >> arr[i];

    for (int j = 0; j < n; j++) {
        int count = 0;
        for (int k = 0; k < j; k++) {
            if (arr[k] < arr[j])
                count++;
        }
        cout << count << ' ';
    }

    return 0;
}
