/*
 * P5743 【深基7.习8】猴子吃桃
 *
 * 题目要求：
 * 小猴买了若干个桃子。第一天刚好吃了这些桃子的一半，又贪嘴多吃了一个；
 * 接下来每一天都会吃剩余桃子的一半外加一个。第 n 天早上起来只剩 1 个桃子，
 * 求小猴一开始买了几个桃子。
 *
 * 输入格式：
 * 输入一个正整数 n，表示天数。
 *
 * 输出格式：
 * 输出小猴一开始买了多少个桃子。
 *
 * 输入样例：
 * 4
 *
 * 输出样例：
 * 22
 *
 * 数据范围：1 ≤ n ≤ 20。
 *
 * 思路：倒推。若当天剩 s 个，则前一天的桃子数为 (s + 1) × 2
 * （前一天吃掉一半多一个后剩下 s）。从第 n 天的 1 个往前推 n-1 次。
 * 本关一次评测通过，无失败记录。
 */

#include <iostream>
using namespace std;

int main()
{
    int n, sum = 1;

    cin >> n;

    for (int i = n - 1; i > 0; i--)
        sum = (sum + 1) * 2;

    cout << sum << endl;
    return 0;
}
