/*
 * P1046 [NOIP 2005 普及组] 陶陶摘苹果
 *
 * 题目要求：
 * 院子里有一棵苹果树，结了 10 个苹果。陶陶有个 30 厘米高的板凳，
 * 当她不能直接用手摘到苹果时，就踩到板凳上再试试。已知 10 个苹果到地面
 * 的高度，以及陶陶把手伸直时能够达到的最大高度，求她能够摘到的苹果数目
 * （碰到苹果即掉下来）。
 *
 * 输入格式：
 * 第一行包含 10 个 100~200 之间的整数（厘米），表示 10 个苹果到地面的高度；
 * 第二行包含一个 100~120 之间的整数，表示陶陶伸手能够达到的最大高度。
 *
 * 输出格式：
 * 输出一行一个整数，表示能够摘到的苹果数目。
 *
 * 输入样例：
 * 100 200 150 140 129 134 167 198 200 111
 * 110
 *
 * 输出样例：
 * 5
 *
 * 说明：踩板凳后可达到 height + 30，苹果高度 ≤ height + 30 即可摘到。
 * 本关一次评测通过，无失败记录。
 */

#include <iostream>
using namespace std;

int main()
{
    int arr[10];
    int height;

    for (int i = 0; i < 10; i++)
        cin >> arr[i];
    cin >> height;

    int count = 0;
    for (int i = 0; i < 10; i++)
        if (arr[i] <= height + 30)
            count++;

    cout << count << endl;
    return 0;
}
