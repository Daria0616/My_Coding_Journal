/*
 * P4956 [COCI 2017/2018 #6] Davor
 *
 * 题目要求：
 * Davor 每周一存入 X 库纳，周二存入 X+K，周三存入 X+2K，……，周日存入 X+6K；
 * 这样连续存 52 周。已知总共筹集到 N 库纳，求 X 和 K。
 * 解一定存在；若有多组解，输出 X 最大且 K 最小的那一组。
 *
 * 输入格式：
 * 输入一个整数 N（1456 ≤ N ≤ 145600）。
 *
 * 输出格式：
 * 第一行输出 X（0 < X ≤ 100），第二行输出 K（K > 0）。
 *
 * 输入样例 1：
 * 1456
 * 输出样例 1：
 * 1
 * 1
 *
 * 输入样例 2：
 * 6188
 * 输出样例 2：
 * 14
 * 1
 *
 * 输入样例 3：
 * 40404
 * 输出样例 3：
 * 99
 * 4
 *
 * 思路：
 * 一周存入之和 = X + (X+K) + ... + (X+6K) = 7X + 21K；
 * 52 周总额 N = 52 × (7X + 21K)，故 N/52 = 7X + 21K。
 * 枚举 X 从 100 往下、K 从 1 往上，找到满足 7X + 21K = N/52 的第一组即可
 * （X 优先取最大、K 取最小）。
 * 本关一次评测通过，无失败记录。
 */

#include <iostream>
using namespace std;

int main()
{
    int N;
    cin >> N;
    N /= 52;

    for (int i = 100; i > 0; i--) {
        for (int j = 1; j < 2000; j++) {
            if (7 * i + 21 * j == N) {
                cout << i << '\n' << j << '\n';
                return 0;
            }
        }
    }

    return 0;
}
