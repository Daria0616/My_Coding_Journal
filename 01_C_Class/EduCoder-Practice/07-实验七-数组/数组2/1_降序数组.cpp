/*
 * 1 降序数组（数组2 · 第1关，实训 4212815，评测 2 次通过）
 *
 * 题目要求：
 * 从键盘输入一个数 data，将其插入到一个已按降序排列的数组中，
 * 插入后数组仍保持降序排列。原数组预置 8 个降序元素，第 9 个位置留给新数。
 *
 * 思路：
 * 先把 data 存到数组末尾 a[8]，再从后往前（逆序）相邻比较：
 * 若 a[k] > a[k-1] 就交换两者并继续前移；一旦 a[k] <= a[k-1]，停止比较。
 *
 * 输入格式：
 * 一行输入一个整数 data。
 *
 * 输出格式：
 * 输出插入后的 9 个数，每个占 5 位宽度（setw(5)），末尾换行。
 *
 * 输入样例 1：22
 * 输出样例 1：   50   25   22   15   10    8    4    2  -10
 *
 * 输入样例 2：-2
 * 输出样例 2：   50   25   15   10    8    4    2   -2  -10
 *
 * 错题复盘：
 * 早期把插入比较写成从前往后遍历：
 *   for (k=1; k<9; k++) { if (a[k]>a[k-1]) 交换; }
 * 错因：新数存在末尾 a[8]，应从末尾向前（k=8→1）相邻比较、边比边前移；方向写成从前往后，新数无法移动到正确位置。
 * 最终改为 for (k=8; k>=1; k--)，
 * 遇到 a[k]<=a[k-1] 即 break 停止。
 */

#include <iostream>
#include <iomanip>
using namespace std;

int main()
{
    int data, temp, k;
    int a[9] = {50, 25, 15, 10, 8, 4, 2, -10};
    cout << "Enter a data:" << endl;
    cin >> data;
    // 请在Begin-End之间添加你的代码，
    // 将输入的data，按降序排列到a数组中//
    /********** Begin *********/
    a[8] = data;
    for (k = 8; k >= 1; k--) {
        if (a[k] > a[k - 1]) {
            temp = a[k];
            a[k] = a[k - 1];
            a[k - 1] = temp;
        }
        else break;
    }

    /********** End **********/
    for (k = 0; k < 9; k++)
        cout << setw(5) << a[k];
    cout << "\n";
    return 0;
}
