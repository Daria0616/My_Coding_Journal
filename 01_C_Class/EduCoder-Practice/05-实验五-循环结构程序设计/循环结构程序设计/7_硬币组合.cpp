/*
 * 7_硬币组合
 *
 * 题目要求：
 * 用 1 分、2 分、5 分硬币凑成 1 元（100 分）。每种硬币个数大于 0，且个数为 5 的倍数，
 * 枚举所有满足 1*i + 2*j + 5*k = 100 的组合并输出。
 *
 * 输入格式：
 * 无输入。
 *
 * 输出格式：
 * 每行一组组合，格式 1fen:个数,2fen:个数,5fen:个数。
 *
 * 输出样例（节选）：
 * 1fen:5,2fen:10,5fen:15
 * 1fen:5,2fen:35,5fen:5
 */

#include <iostream>
using namespace std;

int main()
{
    int i, j, k; // 分别表示 1 分、2 分、5 分的硬币数
    for (i = 1; i <= 100; i++)
        for (j = 1; j <= 50; j++)
            for (k = 1; k <= 20; k++)
                if (i + j * 2 + k * 5 == 100 && i % 5 == 0 && j % 5 == 0 && k % 5 == 0)
                    cout << "1fen:" << i << ",2fen:" << j << ",5fen:" << k << endl;
    return 0;
}
