/*
 * 2_空气质量
 *
 * 题目要求：
 * 输入空气质量 PM2.5 的值 PM，按区间分级输出：
 *   PM ≥ 75      ：空气污染，尽量减少外出
 *   35 ≤ PM < 75 ：空气良好，可适度户外活动
 *   0 ≤ PM < 35  ：空气优质，建议户外活动
 *   PM < 0       ：输入有误
 *
 * 输入格式：
 * 输入一个整数 PM2.5 数值。
 *
 * 输出格式：
 * 输出对应等级的中文提示。
 *
 * 输入样例 1：
 * 80
 * 输出样例 1：
 * 空气污染，尽量减少外出
 *
 * 输入样例 2：
 * -10
 * 输出样例 2：
 * 输入有误
 *
 * 错题复盘（评测 2 次）：
 * 第一次提交“共有 3 组测试集，其中有 2 组测试结果不匹配”。
 * 分级区间判断正确，但提示文案与题目要求不一致：把“输入有误”写成“输入错误”、
 * 把“空气优质”写成“空气优良”，文字不匹配导致对应测试集失败；
 * 改回题目规定的文案后第二次评测通过。
 * 提交记录截图：../../images/4212809-2_空气质量_提交记录.png
 */

#include <iostream>
using namespace std;

int main()
{
    int PM;
    cin >> PM;
    if (PM >= 35)
    {
        if (PM < 75)
            cout << "空气良好，可适度户外活动" << endl;
        else
            cout << "空气污染，尽量减少外出" << endl;
    }
    else
    {
        if (PM < 0)
            cout << "输入有误" << endl;
        else
            cout << "空气优质，建议户外活动" << endl;
    }
    return 0;
}
