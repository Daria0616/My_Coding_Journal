/*
 * 3_求分段函数的值
 *
 * 题目要求：
 * 用 if...else 嵌套计算分段函数 y 的值：
 *   x ≤ -10   ：y = 2x
 *   -10 < x ≤ 0：y = x + 2
 *   0 < x ≤ 10 ：y = x - 2
 *   x > 10     ：y = x / 10
 * 输出用 showpoint 显示小数点及尾随零。
 *
 * 输入格式：
 * 输入一个实数 x。
 *
 * 输出格式：
 * 输出 x=值, y=值。
 *
 * 输入样例 1：
 * -12
 * 输出样例 1：
 * x=-12.0000,y=-24.0000
 *
 * 输入样例 2：
 * 10
 * 输出样例 2：
 * x=10.0000,y=8.00000
 *
 * 错题复盘（评测 7 次）：
 * 前六次多次出现“4 组测试集全不匹配 / 2 组不匹配”。
 * 主要问题：分段区间边界（≤ 与 <）划分不准、if-else 嵌套归属不清，
 * 早期把 -10、0、10 这些分界点归入了错误区间；
 * 整理为四段嵌套判断（x≤0 内再分 x≤-10，x>0 内再分 x≤10），
 * 并核对输出 showpoint 格式后，第七次评测通过。
 * 提交记录截图：../../images/4212808-3_求分段函数的值_提交记录.png
 */

#include <iostream>
#include <iomanip>
using namespace std;

int main()
{
    float x, y;
    cin >> x;
    if (x <= 0)
    {
        if (x <= -10)
            y = x * 2;
        else
            y = 2 + x;
    }
    else
    {
        if (x <= 10)
            y = x - 2;
        else
            y = x / 10;
    }
    cout << setiosflags(ios::showpoint) << "x=" << x << "," << "y=" << y << endl;
    return 0;
}
