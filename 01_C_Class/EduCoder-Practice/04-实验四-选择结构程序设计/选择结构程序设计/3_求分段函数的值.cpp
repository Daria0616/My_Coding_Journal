/*
 * 3_求分段函数的值
 *
 * 题目要求：
 * 用 if...else 嵌套计算分段函数 y 的值：
 *   x ≤ -10   ：y = 2x
 *   -10 < x ≤ 0：y = x + 2
 *   0 < x ≤ 10 ：y = x - 2
 *   x > 10     ：y = x / 10
 * 输出用 showpoint 显示小数点及尾随零。
 *
 * 输入格式：
 * 输入一个实数 x。
 *
 * 输出格式：
 * 输出 x=值, y=值。
 *
 * 输入样例 1：
 * -12
 * 输出样例 1：
 * x=-12.0000,y=-24.0000
 *
 * 输入样例 2：
 * 10
 * 输出样例 2：
 * x=10.0000,y=8.00000
 *
 * 错题复盘（评测 7 次）：前六次失败，分两个阶段。
 *
 * 【早期失败代码（2026-10-28 10:02:22，2 组不匹配）——分支嵌套归属错位】
 *   if (x <= 10) {
 *       y = x - 2;
 *       if (x <= 0) { y = x + 2; }
 *       else        { y = 2 * x; }
 *   } else {
 *       y = x / 10;
 *   }
 * 【错因】区间归属错位：2x（应 x≤-10）被放到了 x>0 一侧；x+2（-10<x≤0）
 *  与 x-2（0<x≤10）的覆盖关系混乱，分界点 -10、0、10 没分进正确区间。
 *
 * 【后期失败代码（2026-10-28 10:12:35，4 组不匹配）——分支已改对，输出格式错】
 *   cout << fixed << setprecision(4) << "x=" << x << "y=" << y << endl;
 * 【错因】① 用 fixed+setprecision(4) 控制格式，题目要求 showpoint 显示小数点及尾随零；
 *  ② "x=" 与 "y=" 之间漏了逗号；③ 还重复粘贴了一段分支判断。
 *
 * 【正确做法（下方代码）】四段嵌套：x≤0 内再分 x≤-10；x>0 内再分 x≤10；
 *  输出用 setiosflags(ios::showpoint)，标签为 "x="<<x<<","<<"y="<<y。
 */

#include <iostream>
#include <iomanip>
using namespace std;

int main()
{
    float x, y;
    cin >> x;
    if (x <= 0)
    {
        if (x <= -10)
            y = x * 2;
        else
            y = 2 + x;
    }
    else
    {
        if (x <= 10)
            y = x - 2;
        else
            y = x / 10;
    }
    cout << setiosflags(ios::showpoint) << "x=" << x << "," << "y=" << y << endl;
    return 0;
}
