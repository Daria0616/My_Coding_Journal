/*
 * 5_数字反序
 *
 * 题目要求：
 * 输入一个三位整数 i，分别求出个位、十位、百位数字，
 * 再按 个位×100 + 十位×10 + 百位 重新拼接，输出反序后的三位数。
 *
 * 输入格式：
 * 输入一个三位整数。
 *
 * 输出格式：
 * 输出反序后的三位数。
 *
 * 输入样例：
 * 123
 *
 * 输出样例：
 * 321
 *
 * 错题复盘（评测 3 次）：
 * 前两次提交均“共有 2 组测试集，其中有 2 组测试结果不匹配”。
 *
 * 【错误代码（早期提交，拆分数字与输出段）】
 *   ge  = a % 10;
 *   shi = a / 10 % 10;
 *   bai = a / 100;
 *   cout << ge * 100 + shi + bai << endl;
 *
 * 【错因】两处问题：① 拆分数字时误把输入变量 i 写成了未定义的 a，变量名笔误；
 *  ② 反序拼接时十位漏乘 10，写成 `ge*100 + shi + bai`，应为 `ge*100 + shi*10 + bai`。
 * 【修正】变量名统一改回 i，并补上 shi*10 后第三次评测通过，即下方代码。
 */

#include <iostream>
using namespace std;

int main()
{
    int i, ge, shi, bai; // i 表示整数，ge、shi、bai 分别表示个位、十位、百位数字
    cin >> i;
    ge = i % 10;
    shi = i / 10 % 10;
    bai = i / 100;
    cout << ge * 100 + shi * 10 + bai << endl;
    return 0;
}
