/*
 * 1_同构数
 *
 * 题目要求：
 * 输入 n（1~100），找出 n 以内的所有同构数。
 * 同构数：一个数的平方末尾几位恰好等于它本身，如 5 是 25 右边的数，25 是 625 右边的数。
 * 检测：j=i*i，若 i==j%10 或 i==j%100 即为同构数。
 * 100 以内同构数：1、5、6、25、76。
 *
 * 输入格式：
 * 输入一个整数 n。
 *
 * 输出格式：
 * 逐个输出 n 以内的同构数。
 *
 * 输入样例：
 * 20
 *
 * 输出样例：
 * 1 5 6
 *
 * 错题复盘（评测 4 次）：
 * 前 3 次“共有 3 组测试集，其中有 3 组测试结果不匹配”。
 * 对比失败代码：把平方固定写成 j=n*n（只对输入 n 平方），再在 1~100 里用这个固定 j 取模判断，
 * 检测对象搞错——正确做法是对每个 i 求 i*i，再判断平方末尾是否等于 i。改为循环内 j=i*i 后通过。
 * 提交记录截图：../../images/4212811-1_同构数_提交记录.png
 */

#include <iostream>
using namespace std;

int main()
{
    int n;
    cin >> n;
    for (int i = 1; i <= n; i++)
    {
        int j = i * i;
        if (i == j % 10 || i == j % 100)
            cout << i << endl;
    }
    return 0;
}
