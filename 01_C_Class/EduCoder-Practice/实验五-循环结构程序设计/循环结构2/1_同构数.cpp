/*
 * 1_同构数
 *
 * 题目要求：
 * 输入 n（1~100），找出 n 以内的所有同构数。
 * 同构数：一个数的平方末尾几位恰好等于它本身，如 5 是 25 右边的数，25 是 625 右边的数。
 * 检测：j=i*i，若 i==j%10 或 i==j%100 即为同构数。
 * 100 以内同构数：1、5、6、25、76。
 *
 * 输入格式：
 * 输入一个整数 n。
 *
 * 输出格式：
 * 逐个输出 n 以内的同构数。
 *
 * 输入样例：
 * 20
 *
 * 输出样例：
 * 1 5 6
 *
 * 错题复盘（评测 4 次）：前 3 次“共有 3 组测试集，其中有 3 组测试结果不匹配”。
 *
 * 【最早失败代码（2026-10 提交，弹窗记录）——平方固定成 n²】
 *   int n, j;
 *   cin >> n;
 *   j = n * n;                       // 只对输入 n 平方
 *   for (int i = 1; i <= 100; i++)
 *       if (i == j % 10 || i == j % 100) cout << i << endl;
 *
 * 【错因】把平方固定成 n²，再用这个固定 j 取模判断，检测对象搞错；循环还写死到 100 而非 n。
 *
 * 【后期失败代码——已改 j=i*i，但循环体缺大括号】
 *   int n, j;
 *   cin >> n;
 *   for (int i = 1; i <= n; i++)
 *       int j = i * i;               // 只有这一句属循环
 *       if (i == j % 10 || i == j % 100) cout << i << endl;  // if 跑到循环外
 *
 * 【错因】for 循环体没加大括号，平方语句之后的 if 判断脱离了循环；j 还被重复声明。
 * 【修正】循环内 j = i*i，并用大括号把平方与判断都包进循环，即下方代码。
 */

#include <iostream>
using namespace std;

int main()
{
    int n;
    cin >> n;
    for (int i = 1; i <= n; i++)
    {
        int j = i * i;
        if (i == j % 10 || i == j % 100)
            cout << i << endl;
    }
    return 0;
}
