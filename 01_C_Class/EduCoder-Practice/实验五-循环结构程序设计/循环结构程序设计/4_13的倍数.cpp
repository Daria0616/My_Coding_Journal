/*
 * 4_13的倍数
 *
 * 题目要求：
 * 输入 n，求 n 以内最大的 13 的倍数。从 n 开始向下遍历，遇到第一个能被 13 整除的数
 * 用 break 跳出并输出；n < 13 时输出“无效数字”。
 *
 * 输入格式：
 * 输入一个整数 n。
 *
 * 输出格式：
 * 输出 n 以内最大的 13 倍数；不足 13 时输出 无效数字。
 *
 * 输入样例 1：
 * 100
 * 输出样例 1：
 * 91
 *
 * 输入样例 2：
 * 10
 * 输出样例 2：
 * 无效数字
 *
 * 错题复盘（评测 2 次）：
 * 第一次提交“共有 4 组测试集，其中有 3 组测试结果不匹配”。
 * 对比失败代码：循环里把判断写成了普通表达式语句 `i%13==0; break;`，漏写 if，
 * 导致每轮都直接 break，输出的是 n 本身而非 13 倍数；补上 if 条件判断后第二次通过。
 * 提交记录截图：../../images/4212810-4_13的倍数_提交记录.png
 */

#include <iostream>
using namespace std;

int main()
{
    int n, i;
    cin >> n;
    if (n >= 13)
    {
        for (i = n; i >= 0; i--)
        {
            if (i % 13 == 0)
                break;
        }
        cout << i << endl;
    }
    else
        cout << "无效数字" << endl;
    return 0;
}
