/*
 * 7-5 二维数组周边元素之和
 *
 * 题目要求：
 * 输入二维数组的行数 n 和列数 m，再输入二维数组各项数据，
 * 计算该二维数组周边（最外圈）元素之和，注意避免四个角重复计算。
 * 计算分两步：
 *   1. 按行累加首行和末行的所有元素；
 *   2. 按列累加中间各行的首列和末列元素。
 *
 * 输入格式：
 * 第一行输入两个整数 n、m（行数、列数）；
 * 接下来 n 行，每行 m 个整数。
 *
 * 输出格式：
 * 输出周边元素之和，格式为 sum=和。
 *
 * 输入样例：
 * 4  5
 * 1  3  5  7  9
 * 2  9  9  9  4
 * 6  9  9  9  8
 * 1  3  5  7  0
 *
 * 输出样例：
 * sum=61
 */

#include <iostream>
using namespace std;
int main()
{
    int a[10][10];
    int n, m, i, j; // n 表示数组行数，m 表示数组列数
    cin >> n >> m;  // 分别输入二维数组的行和列
    for (i = 0; i < n; i++)
        for (j = 0; j < m; j++)
            cin >> a[i][j];

    // 请在 Begin-End 之间添加你的代码，
    /* (1) 输入二维数组 a 的行数和列数，再输入二维数组各项数据，
       (2) 计算二维数组周边元素之和，注意避免重复计算，
         若数组如下所示：
           1    3    5    7    9
           2    9    9    9    4
           6    9    9    9    8
           1    3    5    7    0
    */
    // (3) 按题意计算结果：1+3+5+7+9+2+4+6+8+1+3+5+7+0 //
    /********** Begin *********/
    int sum = 0;
    for (int j = 0; j < m; j++)
        sum += a[0][j] + a[n - 1][j];
    for (int i = 1; i < n - 1; i++)
        sum += a[i][0] + a[i][m - 1];

    cout << "sum=" << sum << endl;
    /********** End **********/

    return 0;
}
