/*
 * 7-4 要刷多少题
 *
 * 题目要求：
 * 老师说：想在天梯赛取得好成绩，第一件事是把前面 n 年的天梯赛真题做一遍。
 * 已知每年的天梯赛有 15 道题目，全新不重复。请算一下一共要刷多少道真题。
 *
 * 输入格式：
 * 输入第一行给出一个正整数 n（≤10），为老师提出的比赛年数。
 *
 * 输出格式：
 * 在一行中输出学生需要做完的题目总数。
 *
 * 输入样例：
 * 2
 *
 * 输出样例：
 * 30
 */

#include <stdio.h>

int main()
{
    int n;
    scanf("%d", &n);
    printf("%d\n", 15 * n);
    return 0;
}
