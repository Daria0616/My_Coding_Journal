/*
 * 7-2 计算摄氏温度
 *
 * 题目要求：
 * 编写程序，计算华氏温度对应的摄氏温度。
 * 计算公式：C = 5 × (F − 32) / 9，式中 C 表示摄氏温度，F 表示华氏温度，
 * 输入输出数据要求为整型。
 *
 * 输入格式：
 * 输入一个不超出 1000 的整数，作为华氏温度。
 *
 * 输出格式：
 * 按照下列格式输出：
 * fahr = 输入的华氏温度,  celsius = 计算所得摄氏温度的整数值
 *
 * 输入样例：
 * 100
 *
 * 输出样例：
 * fahr = 100, celsius = 37
 */

#include <stdio.h>

int main()
{
    int C, F;
    scanf("%d", &F);
    C = 5 * (F - 32) / 9;
    printf("fahr = %d,", F);
    printf(" celsius = %d", C);
    return 0;
}
