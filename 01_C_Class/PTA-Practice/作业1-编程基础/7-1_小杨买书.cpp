/*
 * 7-1 小杨买书
 *
 * 题目要求：
 * 小杨同学积攒了一部分零用钱想要用来购买书籍，已知一本书的单价是 13 元，
 * 请根据小杨零用钱的金额，编写程序计算可以购买多少本书，还剩多少零用钱。
 *
 * 输入格式：
 * 输入一个正整数 m，表示小杨拥有的零用钱数。
 *
 * 输出格式：
 * 输出包含两行，第一行购买图书的本数；第二行剩余的零用钱数。
 *
 * 输入样例 1：
 * 100
 *
 * 输出样例 1：
 * 7
 * 9
 *
 * 输入样例 2：
 * 199
 *
 * 输出样例 2：
 * 15
 * 4
 */

#include <stdio.h>

int main()
{
    int m;
    scanf("%d", &m);
    printf("%d\n", m / 13);
    printf("%d", m % 13);
    return 0;
}
