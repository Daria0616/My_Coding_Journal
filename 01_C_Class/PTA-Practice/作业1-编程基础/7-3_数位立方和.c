/*
 * 7-3 数位立方和
 *
 * 题目要求：
 * 对于输入的一个三位整数 n，输出 n 中三个数字立方的和。
 *
 * 输入格式：
 * 输入在一行中给出 1 个三位整数 n。
 *
 * 输出格式：
 * 输出 n 中三个数字立方的和。
 *
 * 输入样例：
 * 112
 *
 * 输出样例：
 * 10
 */

#include <stdio.h>

int main()
{
    int n, a, b, c;
    scanf("%d", &n);
    a = n / 100;
    b = (n - 100 * a) / 10;
    c = n % 10;
    printf("%d", a * a * a + b * b * b + c * c * c);
    return 0;
}
