/*
 * R7-1 计算长方形的周长和面积
 *
 * 题目要求：
 * 输入长方形的长和宽，计算长方形的周长和面积。
 *
 * 输入格式：
 * 在一行中给出两个整数（<=10^5）。
 *
 * 输出格式：
 * 第一行长方形的周长；第二行长方形的面积。
 *
 * 输入样例：
 * 6 8
 *
 * 输出样例：
 * 周长 = 28
 * 面积 = 48
 *
 * 说明：
 * 长宽可达 10^5，乘积可能较大，故用 long long 存储。
 * 周长 = 2×(长+宽)，面积 = 长×宽。
 */

#include <stdio.h>

int main()
{
    long long int a, b;
    scanf("%lld %lld", &a, &b);
    printf("周长 = %lld\n", 2 * (a + b));
    printf("面积 = %lld\n", a * b);
    return 0;
}
