/*
 * 7-13 计算年初总天数
 *
 * 题目要求：输入一个年份，求出从公元 1 年 1 月 1 日到这一年的 1 月 1 日
 * 总共有多少天。限定不能使用循环结构。置闰规则：四闰百不闰，四百闰。
 *
 * 输入样例：
 * 2021
 * 输出样例：
 * 737791
 *
 * 推导：前面完整年数 y=year-1；闰年数 leap=y/4-y/100+y/400；
 *       总天数 = y*365 + leap + 1（含当年 1 月 1 日当天）。
 */

#include <stdio.h>

int main()
{
    int year;
    scanf("%d", &year);

    int y = year - 1;
    int leap = y / 4 - y / 100 + y / 400;

    printf("%d\n", y * 365 + leap + 1);
    return 0;
}
