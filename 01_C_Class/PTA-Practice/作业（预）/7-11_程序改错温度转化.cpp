/*
 * 7-11 程序改错：温度转化
 *
 * 题目要求：输入一个华氏温度，求出对应的摄氏温度。
 * 换算关系 C=5/9(F-32)，输出摄氏温度，保留两位小数，最后换行。
 *
 * 原始错误代码：
 *   #include <stdio.h>;
 *   int main(void);
 *   {int f,c;
 *    scanf("%d%d",f,c);
 *    c=5/9(f-32);
 *    printf("摄氏温度=%d\n",c)；
 *    return 0
 *   }
 *
 * 改错要点：
 * 1. 去掉头文件/主函数后的多余分号；scanf 参数要取地址 &f。
 * 2. 5/9 是整数除法得 0，应写 5.0/9 做浮点除法。
 * 3. 温度用 float，输出 %.2f 保留两位小数。
 *
 * 输入样例：
 * 100
 * 输出样例：
 * 37.78
 */

#include <stdio.h>

int main()
{
    float f, c;
    scanf("%f", &f);

    c = 5.0 / 9 * (f - 32);

    printf("摄氏温度=%.2f\n", c);
    return 0;
}
