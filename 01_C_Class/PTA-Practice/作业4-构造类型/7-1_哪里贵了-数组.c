/*
 * 7-1 哪里贵了-数组
 *
 * 题目要求：
 * 为每一种商品打折扣。如果一个商品的价格超过了所有商品的平均价格，
 * 就认为定价过高，该商品打 9 折；其他商品价格保持不变。
 * 请计算每种商品折扣后的价格。
 *
 * 输入格式：
 * 共 2 行。
 * 第 1 行：商品的数量 n。
 * 第 2 行：n 个浮点数，表示每种商品的价格。
 *
 * 输出格式：
 * n 个浮点数，表示每种商品折扣后的价格（保留至小数点后 1 位），
 * 中间以一个空格分割，末尾不得有多余的空格。
 *
 * 输入样例：
 * 8
 * 40.3 90.2 74.3 34.4 33.1 32.1 12.6 69.8
 *
 * 输出样例：
 * 40.3 81.2 66.9 34.4 33.1 32.1 12.6 62.8
 *
 */

#include <stdio.h>
int main(){
    int n;
    float sum=0;
    float p[100];
    scanf("%d",&n);
    for (int i=0;i<n;i++){
        scanf("%f",&p[i]);
        sum+=p[i];
    }
    float average=sum/n;
    for (int i=0;i<n;i++){
        if (p[i]>average)
            p[i]*=0.9;
    }
    for (int i=0;i<n-1;i++)
        printf("%.1f ",p[i]);
    printf("%.1f\n",p[n-1]);
    return 0;
}
